// 201.1 Letters: د ذ ا ر ز و — find the letter, its Arabic name, its Hebrew counterpart.
const F = require('./facts');
const { ar, lesson, q, others } = require('./common');

const HE = F.LETTERS.map((l) => l.he);
const NAMES = F.LETTERS.map((l) => l.name);
const AR = F.LETTERS.map((l) => l.ar);
const L = (a) => F.letter(a);

const rows = F.LETTERS.map((l) =>
  `<tr><td>${ar(l.ar)}</td><td>${l.name}</td><td>${l.he}</td><td>${l.note}</td></tr>`).join('\n');

const theoryContentHe = `
<h2>שש אותיות ראשונות</h2>

<p>בשיעור הזה לומדים לזהות שש אותיות ערביות: לדעת איך קוראים להן בערבית ולאיזו אות עברית כל אחת מקבילה. כותבים ערבית מימין לשמאל, כמו עברית.</p>

<h3>כלל 1: האותיות, השמות והאותיות המקבילות</h3>
<table class="letters-table">
<tr><th>האות</th><th>השם בערבית</th><th>בעברית</th><th>איך מזהים</th></tr>
${rows}
</table>

<h3>כלל 2: נקודה אחת עושה אות אחרת</h3>
<div class="rules">
  <p>שני זוגות נראים כמעט אותו דבר, וההבדל הוא נקודה אחת מעל:</p>
  <ul>
    <li>${ar('د')} דאל (ד) – בלי נקודה; ${ar('ذ')} ד׳אל (ד׳) – עם נקודה מעל.</li>
    <li>${ar('ر')} רא (ר) – בלי נקודה; ${ar('ز')} זאי (ז) – עם נקודה מעל.</li>
  </ul>
</div>

<h3>כלל 3: מוצאים את האות בתוך מילה</h3>
<div class="rules">
  <p>קוראים את המילה מימין לשמאל ובודקים כל אות. למשל במילה ${ar('وَرْد')} (ורדים) יש ${ar('و')} ואו, ${ar('ر')} רא ו-${ar('د')} דאל.</p>
</div>

<div class="warning">
  <strong>שימו לב:</strong> ${ar('د')} ו-${ar('ذ')} נבדלות רק בנקודה, וגם ${ar('ر')} ו-${ar('ز')}. לפני שעונים, מסתכלים אם יש נקודה מעל האות.
</div>

<div class="tip">
  <strong>טיפ:</strong> שש האותיות האלה לא מתחברות לאות שבאה אחריהן במילה, ולכן קל לראות כל אחת מהן לבד.
</div>
`;

const letterIn = (w) => w.letters.map(([l]) => (l === F.HAMZA_ALIF ? F.PLAIN_ALIF : l));

const questions = [
  // easy: Hebrew counterpart of each letter; the name of four of them
  ...F.LETTERS.map((l, i) => q('easy', `לאיזו אות בעברית מקבילה האות ${l.ar}?`, l.he, others(HE, l.he, 3, i),
    `${l.ar} היא ${l.name}, והיא מקבילה ל-${l.he}.`)),
  ...['د', 'ر', 'ز', 'و'].map((a, i) => q('easy', `מה השם של האות ${a}?`, L(a).name, others(NAMES, L(a).name, 3, i + 2),
    `${a} נקראת ${L(a).name} (${L(a).he}).`)),

  // medium: the two remaining names; from the name to the letter; the letter in a word
  ...['ذ', 'ا'].map((a, i) => q('medium', `מה השם של האות ${a}?`, L(a).name, others(NAMES, L(a).name, 3, i + 4),
    `${a} נקראת ${L(a).name} (${L(a).he}).`)),
  q('medium', 'איזו מהאותיות היא ד׳אל?', 'ذ', ['د', 'ز', 'ر'], 'ד׳אל היא ذ: כמו דאל (د) עם נקודה מעל.'),
  q('medium', 'איזו מהאותיות היא זאי?', 'ز', ['ر', 'ذ', 'و'], 'זאי היא ز: כמו רא (ر) עם נקודה מעל.'),
  q('medium', 'איזו מהאותיות היא רא?', 'ر', ['ز', 'د', 'ا'], 'רא היא ر, בלי נקודה.'),
  q('medium', 'איזו מהאותיות היא ואו?', 'و', ['د', 'ر', 'ذ'], 'ואו היא و, עם ראש עגול וזנב.'),
  q('medium', 'באיזו מילה יש את האות ز?', 'أَرْز', ['وَرْد', 'دَار', 'وِدَاد'],
    'ב-أَرْز (ארזים) יש ز בסוף. בשאר המילים אין זאי.'),
  q('medium', 'באיזו מילה יש את האות و?', 'وَرْد', ['دَار', 'أَرْز', 'زَارَ'],
    'ב-وَرْد (ורדים) יש و בהתחלה. בשאר המילים אין ואו.'),
  q('medium', 'באיזו מילה יש את האות ر?', 'دَار', ['وِدَاد', 'دَاوُد', 'أَو'],
    'ב-دَار (בית) יש ر בסוף. בשאר המילים אין רא.'),
  q('medium', 'באיזו מילה אין את האות د?', 'زَارَ', ['دَار', 'وَرْد', 'أَرَادَ'],
    'ב-زَارَ יש ز, ا ו-ر, בלי د. בכל שאר המילים יש דאל.'),

  // hard: telling the look-alikes apart, counting, the letters of a word
  q('hard', 'מה ההבדל בין ذ ל-د?', 'ל-ذ יש נקודה מעל', ['ל-د יש נקודה מעל', 'ל-ذ יש נקודה מתחת', 'אין ביניהן הבדל'],
    'ذ (ד׳אל) היא د (דאל) עם נקודה אחת מעל.'),
  q('hard', 'מה ההבדל בין ز ל-ر?', 'ל-ز יש נקודה מעל', ['ל-ر יש נקודה מעל', 'ל-ز יש שתי נקודות', 'אין ביניהן הבדל'],
    'ز (זאי) היא ر (רא) עם נקודה אחת מעל.'),
  q('hard', 'כמה פעמים מופיעה האות د במילה دَاوُد?', '2', ['1', '3'],
    'دَاوُد: د בהתחלה ו-د בסוף, כלומר פעמיים.'),
  q('hard', 'כמה פעמים מופיעה האות د במילה وِدَاد?', '2', ['1', '3'],
    'وِدَاد: ו, ד, א, ד – הדאל מופיעה פעמיים.'),
  q('hard', 'איזו אות לא מופיעה במילה وَرْد?', 'ز', ['و', 'ر', 'د'],
    'וַרְד = و + ر + د. אין בה זאי.'),
  q('hard', 'איזו אות לא מופיעה במילה زَارَ?', 'د', ['ز', 'ا', 'ر'],
    'זַארַ = ز + ا + ر. אין בה דאל.'),
  q('hard', `איזה צירוף אותיות מתחיל באות ד׳אל? (צירופי אותיות, לא מילים)`, F.DHAL_PAIRS[1], ['دُو', 'زُو', 'رُو'],
    `${F.DHAL_PAIRS[1]} מתחיל ב-ذ (ד׳אל), שיש לה נקודה מעל. دُو מתחיל ב-د, בלי נקודה.`),
  q('hard', 'לאיזו אות עברית מקבילה האות שבתחילת המילה وِدَاد?', 'ו', ['ד', 'א', 'ר'],
    'המילה מתחילה ב-و (ואו), שמקבילה ל-ו.'),
  q('hard', 'אילו אותיות עבריות מקבילות לאותיות של המילה دَار?', 'ד, א, ר', ['ד, ו, ר', 'ז, א, ר', 'ד, א, ז'],
    `دَار = ${letterIn(F.word('دَار')).map((a) => `${a} (${L(a).he})`).join(' + ')}.`),
  q('hard', 'אילו אותיות עבריות מקבילות לאותיות של המילה أَرْز?', 'א, ר, ז', ['א, ד, ז', 'א, ר, ד', 'ו, ר, ז'],
    'أَرْز = أ (א) + ر (ר) + ز (ז).')
];

module.exports = lesson({
  topicNumber: 201,
  subtopicNumber: '201.1',
  titleEn: 'Letters: dal, dhal, alif, ra, zay, waw',
  titleHe: 'אותיות: د ذ ا ر ز و',
  orderIndex: 2001,
  theoryContentHe
}, questions);
