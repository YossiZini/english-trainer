// 201.4 The eight words: read them and know their Hebrew meaning.
const F = require('./facts');
const { ar, lesson, q, others } = require('./common');

const W = (a) => F.word(a);
const MEANINGS = F.WORDS.map((w) => w.short);
const ARABIC = F.WORDS.map((w) => w.ar);
const READINGS = F.WORDS.map((w) => w.read);

const rows = F.WORDS.map((w) =>
  `<tr><td>${ar(w.ar)}</td><td>${w.read}</td><td>${w.meaning}</td></tr>`).join('\n');

const theoryContentHe = `
<h2>שמונה מילים ראשונות</h2>

<p>אלה המילים של היחידה. צריך לדעת לקרוא כל מילה (עם התנועות) ולדעת את הפירוש שלה בעברית. לא צריך לדעת לכתוב אותן.</p>

<h3>כלל 1: המילים, הקריאה והפירוש</h3>
<table class="letters-table">
<tr><th>המילה</th><th>איך קוראים</th><th>פירוש</th></tr>
${rows}
</table>

<h3>כלל 2: קוראים אות-אות, מימין לשמאל</h3>
<div class="rules">
  <p>כל מילה בנויה מהאותיות והתנועות שכבר למדנו. למשל ${ar('وَرْد')}: ${ar('وَ')} וַ + ${ar('رْ')} רְ + ${ar('د')} ד = וַרְד, ורדים.</p>
  <p>${ar('أَرَادَ')}: ${ar('أَ')} אַ + ${ar('رَ')} רַ + ${ar('ا')} (מאריכה) + ${ar('دَ')} דַ = אַרַאדַ, רצה.</p>
</div>

<h3>כלל 3: שתי המילים שקל לבלבל</h3>
<div class="rules">
  <ul>
    <li>${ar('دَار')} דַאר – בית (וגם דירה או משפחה). מתחילה ב-${ar('د')}.</li>
    <li>${ar('زَارَ')} זַארַ – ביקר. מתחילה ב-${ar('ز')} (עם נקודה!) ונגמרת בפתחה.</li>
  </ul>
  <p>וגם: ${ar('أَرْز')} אַרְז – ארזים (עצים), לעומת ${ar('أَرَادَ')} אַרַאדַ – רצה.</p>
</div>

<div class="warning">
  <strong>שימו לב:</strong> ${ar('وِدَاد')} ודאד הוא שם של <strong>בת</strong>, ${ar('دَاوُد')} דאוד הוא שם של <strong>בן</strong>. שניהם מתחילים באות אחרת: ודאד ב-${ar('و')}, דאוד ב-${ar('د')}.
</div>

<div class="tip">
  <strong>טיפ:</strong> ${ar('أَو')} (אַו) פירושה "או", בדיוק כמו בעברית: תה או קפה.
</div>
`;

const questions = [
  // easy: meaning of each word
  ...F.WORDS.map((w, i) => q('easy', `מה הפירוש של המילה ${w.ar}?`, w.short, others(MEANINGS, w.short, 3, i),
    `${w.ar} נקראת ${w.read} ופירושה ${w.meaning}.`)),
  q('easy', 'איזו מילה פירושה "בית"?', 'دَار', ['زَارَ', 'وَرْد', 'أَرْز'], 'دَار (דַאר) = בית, דירה, משפחה.'),
  q('easy', 'איזו מילה פירושה "ורדים"?', 'وَرْد', ['أَرْز', 'دَار', 'وِدَاد'], 'وَرْد (וַרְד) = ורדים.'),

  // medium: readings and meaning → word
  q('medium', 'איזו מילה פירושה "ארזים"?', 'أَرْز', ['أَرَادَ', 'وَرْد', 'أَو'], 'أَرْز (אַרְז) = ארזים. أَرَادَ = רצה.'),
  q('medium', 'איזו מילה פירושה "רצה"?', 'أَرَادَ', ['زَارَ', 'أَرْز', 'دَاوُد'], 'أَرَادَ (אַרַאדַ) = רצה (רצה משהו).'),
  q('medium', 'איזו מילה פירושה "ביקר"?', 'زَارَ', ['أَرَادَ', 'دَار', 'أَو'], 'زَارَ (זַארַ) = ביקר (ביקר במקום).'),
  q('medium', 'איזו מילה פירושה "או"?', 'أَو', ['أَرْز', 'وَرْد', 'زَارَ'], 'أَو (אַו) = או, ברירה.'),
  q('medium', 'איזו מילה היא שם של בת?', 'وِدَاد', ['دَاوُد', 'دَار', 'وَرْد'], 'وِدَاد (וִדַאד) הוא שם פרטי של בת; دَاوُد (דאוד) של בן.'),
  q('medium', 'איזו מילה היא שם של בן?', 'دَاوُد', ['وِدَاد', 'أَرَادَ', 'زَارَ'], 'دَاوُد (דַאוֻד) הוא שם פרטי של בן.'),
  ...['دَار', 'وَرْد', 'أَرْز', 'زَارَ'].map((a, i) => q('medium', `איך קוראים את המילה ${a}?`, W(a).read, others(READINGS, W(a).read, 3, i + 1),
    `${a} = ${W(a).read}: ${W(a).meaning}.`)),

  // hard: reading → meaning, telling similar words apart, full sentences
  ...['وِدَاد', 'دَاوُد', 'أَرَادَ', 'أَو'].map((a, i) => q('hard', `איך קוראים את המילה ${a}?`, W(a).read, others(READINGS, W(a).read, 3, i + 3),
    `${a} = ${W(a).read}: ${W(a).meaning}.`)),
  q('hard', 'מה ההבדל בין دَار ל-زَارَ?', 'دَار = בית, زَارَ = ביקר', ['دَار = ביקר, زَارَ = בית', 'שתיהן = בית', 'دَار = ורדים, زَارَ = ביקר'], 'دَار מתחילה ב-د (בית); زَارَ מתחילה ב-ز עם נקודה (ביקר).'),
  q('hard', 'מה ההבדל בין أَرْز ל-أَرَادَ?', 'أَرْز = ארזים, أَرَادَ = רצה', ['أَرْز = רצה, أَرَادَ = ארזים', 'שתיהן = ארזים', 'أَرْز = או, أَرَادَ = רצה'], 'أَرْز (אַרְז) הם עצי ארז; أَرَادَ (אַרַאדַ) = רצה.'),
  q('hard', 'המילה שנקראת "וִדַאד" היא…', 'שם של בת', ['שם של בן', 'ורדים', 'בית'], 'וִדַאד = وِدَاد, שם פרטי של בת.'),
  q('hard', 'המילה שנקראת "זַארַ" פירושה…', 'ביקר', ['רצה', 'בית', 'ארזים'], 'זַארַ = زَارَ = ביקר במקום כלשהו.'),
  q('hard', 'איזו מילה מתאימה: "דאוד ___ את ודאד" (הלך לראות אותה)?', 'زَارَ', ['أَرَادَ', 'دَار', 'أَو'], 'ביקר = زَارَ. דאוד ביקר את ודאד.'),
  q('hard', 'איזו מילה מתאימה: "דאוד ___ ורדים" (חשק בהם)?', 'أَرَادَ', ['زَارَ', 'وَرْد', 'أَرْز'], 'רצה = أَرَادَ. דאוד רצה ורדים.')
];

module.exports = lesson({
  topicNumber: 201,
  subtopicNumber: '201.4',
  titleEn: 'First words',
  titleHe: 'שמונה מילים ראשונות',
  orderIndex: 2004,
  theoryContentHe
}, questions);
