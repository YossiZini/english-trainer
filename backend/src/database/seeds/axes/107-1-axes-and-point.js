/** Why the point is (x, y): how it is reached from the origin. */
const readIt = (x, y, name = '') => `מראשית הצירים: ${walk(x, y)}. לכן ${at(x, y, name)}.`;

/** The quarter of (x, y), explained by the signs. */
function quarterWhy(x, y) {
  const sx = x > 0 ? 'חיובי' : 'שלילי', sy = y > 0 ? 'חיובי' : 'שלילי';
  const q = QUARTERS[[x > 0 && y > 0, x < 0 && y > 0, x < 0 && y < 0, x > 0 && y < 0].indexOf(true)];
  return `x ${sx} ו-y ${sy}: ${q}.`;
}

