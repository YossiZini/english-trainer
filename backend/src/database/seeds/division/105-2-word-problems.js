/**
 * A story problem on a ÷ d: 'up' (everything needs a place: one more),
 * 'down' (only whole things count: the quotient) or 'rest' (what is left:
 * the remainder). The answer is computed; the wrong options are given.
 */
function story(n, level, text, a, d, kind, wrongs) {
  const { q, r } = split(a, d);
  const answer = kind === 'up' ? q + (r > 0 ? 1 : 0) : kind === 'down' ? q : r;
  const head = `${ltr(`${a} ÷ ${d} = ${q}`)} ושארית ${r}`;
  const why = kind === 'up'
    ? `${q} לא מספיקים, כי גם השארית ${r} צריכה מקום. מוסיפים 1: ${answer}.`
    : kind === 'down'
      ? `השארית ${r} לא מספיקה לעוד אחד שלם, ולכן ${answer}.`
      : `שואלים כמה נשאר, ולכן התשובה היא השארית: ${answer}.`;
  return numberQuestion(n, level, text, answer, wrongs, `${head}: ${why}`, groupsPicture(a, d));
}

