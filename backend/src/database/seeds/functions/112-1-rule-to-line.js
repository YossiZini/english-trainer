// 112.1 מכלל לישר — a rule gives each x one y: from the rule to a table of
// values, the table's points lie on one straight line, y = kx goes through
// the origin, and a point is on the line when the rule gives its y.
const { ltr, P, eq, at, glue, rule, subst, numQ, choiceQ, ruleQ, pointQ, questionGraph, graphPic, tablePic, tableOf, lesson } = require('./common');

const R = (m, b) => ltr(rule(m, b));
const put = (m, b, x) => ltr(subst(m, b, x));
const opt = (m, b) => glue(rule(m, b));
const YES_NO = ['כן', 'לא', 'אי אפשר לדעת'];
const yes = (n, level, text, explanation, opts) => choiceQ(n, level, text, 'כן', YES_NO.filter((w) => w !== 'כן'), explanation, opts);
const no = (n, level, text, explanation, opts) => choiceQ(n, level, text, 'לא', YES_NO.filter((w) => w !== 'לא'), explanation, opts);

const theory = `
<h2>מכלל לישר</h2>

<p>פונקציה היא כלל שנותן לכל מספר x מספר אחד y. הכלל ${eq('y = 2x + 1')} אומר: כופלים את x ב-2 ומוסיפים 1. מהכלל בונים טבלה, מהטבלה מסמנים נקודות במערכת הצירים, והנקודות של כלל כזה נמצאות כולן על ישר אחד. לכן הוא נקרא פונקציה קווית.</p>

<div class="formula">
  <div class="formula-title">פונקציה קווית</div>
  <div class="formula-content">${eq('y = 2x + 1')}</div>
  <div class="formula-explanation">כש-${eq('x = 3')}, ${eq('y = 2 × 3 + 1 = 7')}: הנקודה ${eq('(3, 7)')} על הישר.</div>
</div>

<h3>כלל 1: מציבים x ובונים טבלה</h3>
<div class="rules">
  <p>כדי למצוא את y מציבים את x בכלל ומחשבים. את התוצאות רושמים בטבלת ערכים: למעלה x, ומתחת לכל x ה-y שלו. בכלל ${eq('y = 2x + 1')}: כש-${eq('x = 0')}, ${eq(subst(2, 1, 0))}; כש-${eq('x = −1')}, ${eq(subst(2, 1, -1))}.</p>
  ${tablePic(tableOf(2, 1, [-1, 0, 1, 2]), [], `טבלת ערכים של ${eq('y = 2x + 1')}`)}
</div>

<h3>כלל 2: הנקודות נמצאות על ישר</h3>
<div class="rules">
  <p>כל עמודה בטבלה היא נקודה ${eq('(x, y)')}: ${eq('(−1, −1)')}, ${eq('(0, 1)')}, ${eq('(1, 3)')}, ${eq('(2, 5)')}. מסמנים אותן במערכת הצירים, והן יוצאות על קו ישר אחד. הישר שעובר דרכן הוא הגרף של הפונקציה, וכל נקודה עליו מקיימת את הכלל.</p>
  ${graphPic({ xMin: -3, xMax: 3, yMin: -3, yMax: 6, lines: [{ m: 2, b: 1 }], points: [{ x: -1, y: -1 }, { x: 0, y: 1 }, { x: 1, y: 3 }, { x: 2, y: 5 }] }, `הגרף של ${eq('y = 2x + 1')}`)}
</div>

<h3>כלל 3: ${eq('y = kx')} עובר בראשית הצירים</h3>
<div class="rules">
  <p>כשלא מוסיפים מספר, כמו ב-${eq('y = 2x')}, כש-${eq('x = 0')} גם y הוא 0: הישר עובר בראשית הצירים ${eq('(0, 0)')}. בכל נקודה שלו y גדול פי 2 מ-x, כמו בפרופורציה מפרק 12: ${eq('(1, 2)')}, ${eq('(2, 4)')}, ${eq('(−1, −2)')}. כך גם ${eq('y = −x')}, שבו y הוא הנגדי של x.</p>
  ${graphPic({ lines: [{ m: 2, b: 0, label: 'y = 2x', labelAt: [2.1, 3] }, { m: -1, b: 0, color: 'b', label: 'y = −x', labelAt: [-2.6, 3.4] }], points: [{ x: 0, y: 0 }] }, `שני הישרים עוברים ב-${eq('(0, 0)')}`)}
</div>

<h3>כלל 4: האם הנקודה על הישר?</h3>
<div class="rules">
  <p>נקודה נמצאת על הישר אם הכלל נותן את ה-y שלה. מציבים את ה-x של הנקודה ומשווים. ל-${eq('A(2, 5)')}: ${eq(subst(2, 1, 2))}, כמו ה-y שלה, ולכן היא על הישר ${eq('y = 2x + 1')}. ל-${eq('B(3, 6)')}: ${eq(subst(2, 1, 3))}, ולא 6, ולכן היא לא על הישר: היא מתחתיו.</p>
  ${graphPic({ xMin: -2, xMax: 4, yMin: -2, yMax: 7, lines: [{ m: 2, b: 1 }], points: [{ x: 2, y: 5, label: 'A', at: 'nw' }, { x: 3, y: 6, label: 'B', color: 'b', at: 'se' }] }, `${eq('A(2, 5)')} על הישר, ${eq('B(3, 6)')} לא`)}
</div>

<div class="warning">
  <strong>טעות נפוצה:</strong> להחליף בין x ל-y. בנקודה ${eq('(5, 2)')} ה-x הוא 5, המספר הראשון. מציבים 5: ${eq(subst(2, 1, 5))}, ולא 2, ולכן ${eq('(5, 2)')} לא על הישר ${eq('y = 2x + 1')}. מי שמציב 2 מקבל 5 וחושב בטעות שהיא עליו.
</div>

<div class="tip">
  <strong>טיפ:</strong> כדי לשרטט ישר מספיקות שתי נקודות. נקודה שלישית היא בדיקה: אם היא לא על אותו ישר, יש טעות בחישוב.
</div>
`;

