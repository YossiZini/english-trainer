// 111.1 מהו יחס — a ratio compares two amounts: written a:b and read "a ל-b",
// the order matters, simplifying by a common divisor, equal ratios, and a
// ratio as a part of the whole. Ratios, wrong options and pictures from ./common.js.
const { ltr, P, eq, ratio, simplest, choiceQ, numQ, barPic, lesson } = require('./common');

/** "a:b = c:d" when simplified, with the divisor named. */
function simplifyWhy(terms) {
  const s = simplest(...terms);
  const by = terms[0] / s[0];
  return `מחלקים את כל האיברים ב-${by}: ${ltr(`${ratio(...terms)} = ${ratio(...s)}`)}.`;
}

/** A bar model of a simplified two-term ratio, a part worth `each`. */
const bars = ([a, b], [la, lb], each) => barPic([{ label: la, parts: a, each }, { label: lb, parts: b, each, color: 'b' }], `${ratio(a, b)} בחלקים שווים`);

/** "Simplify a:b": the simplest form, against the reversed, a half-way and a wrong one. */
function simplifyQ(n, level, terms, wrongs) {
  const s = simplest(...terms);
  return choiceQ(n, level, `צמצמו את היחס ${ratio(...terms)}.`, ratio(...s), wrongs, simplifyWhy(terms),
    s.length === 2 && s[0] <= 12 && s[1] <= 12 ? { picture: bars(s, ['', ''], terms[0] / s[0]) } : {});
}

/** The part of the whole: a/(a + b) or b/(a + b). */
const partWhy = (a, b, which) => `ביחס ${ratio(a, b)} יש ${ltr(`${a} + ${b} = ${a + b}`)} חלקים, ומהם ${which} חלקים: ${ltr(`${which}/${a + b}`)}.`;
const wholePic = (a, b) => barPic([{ label: 'השלם', parts: a + b, split: a }], `${a} חלקים כחולים ו-${b} כתומים`);

