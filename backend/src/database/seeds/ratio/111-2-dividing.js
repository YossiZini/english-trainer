// 111.2 חלוקה לפי יחס — sharing an amount in a ratio: count the parts, find
// one part, then each share; from one share to the other and to the whole;
// from the difference between the shares; ratios of three terms.
// Shares, wrong options and pictures from ./common.js.
const { ltr, P, eq, ratio, share, numQ, barPic, lesson } = require('./common');

const COLORS = ['a', 'b', 'a'];

/** The bar model of a ratio with its names, a part worth `one` (null: not written). */
const sharePic = (terms, names, one, caption) =>
  barPic(terms.map((t, i) => ({ label: names[i], parts: t, each: one, color: COLORS[i] })), caption || `כל חלק ${one}`);

/** "a + b = 8 parts, one part 40 ÷ 8 = 5": the first two steps of every share. */
function partsWhy(total, terms) {
  const { parts, one } = share(total, terms);
  return `בסך הכול ${ltr(`${terms.join(' + ')} = ${parts}`)} חלקים. חלק אחד: ${ltr(`${total} ÷ ${parts} = ${one}`)}.`;
}

/**
 * The share of names[ask] when `total` is shared in `terms`. Wrong options:
 * the other share, dividing by the term instead of the sum, and `more`.
 */
function shareQ(n, level, text, total, terms, names, ask, more = []) {
  const { one, shares } = share(total, terms);
  const count = terms[ask] === 1 ? 'חלק אחד' : `${terms[ask]} חלקים`;
  const why = `${partsWhy(total, terms)} ל${names[ask]} ${count}: ${ltr(`${terms[ask]} × ${one} = ${shares[ask]}`)}.`;
  const wrongs = [...more, ...shares.filter((_, i) => i !== ask), total - shares[ask], terms[ask] * terms[(ask + 1) % terms.length]];
  return numQ(n, level, text, shares[ask], wrongs, why, { picture: sharePic(terms, names, one) });
}

