const W = (list, answer) => list.filter((x) => x !== answer);
/** A question on the kind of a triangle by its sides. */
const sidesQ = (n, level, text, answer, why, opts) => choiceQ(n, level, text, answer, [...W(BY_SIDES, answer), BY_ANGLES[1]], why, opts);
/** A question on the kind of a triangle by its angles. */
const anglesQ = (n, level, text, answer, why, opts) => choiceQ(n, level, text, answer, [...W(BY_ANGLES, answer), BY_SIDES[0]], why, opts);
/** Can three lengths make a triangle? */
const canQ = (n, level, [a, b, c]) => {
  const [x, y, z] = [a, b, c].sort((p, q) => p - q);
  const yes = x + y > z;
  return choiceQ(n, level, `האם אפשר לבנות משולש מצלעות של ${a}, ${b} ו-${c} ס״מ?`, yes ? 'כן' : 'לא',
    yes ? ['לא', 'רק משולש ישר-זווית', 'רק משולש שווה שוקיים'] : ['כן', 'רק משולש ישר-זווית', 'רק משולש שווה שוקיים'],
    `בודקים את שתי הצלעות הקצרות: ${ltr(`${x} + ${y} = ${x + y}`)}. ${yes ? `${x + y} גדול מ-${z}, ולכן אפשר.` : `${x + y} ${x + y === z ? 'שווה ל' : 'קטן מ'}-${z}, ולכן שתי הצלעות הקצרות לא נפגשות: אי אפשר.`}`);
};
