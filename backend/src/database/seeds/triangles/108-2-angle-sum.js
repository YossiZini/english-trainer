/** The third angle from two: wrong options from 360°, forgetting one angle, adding them. */
function thirdQ(n, level, a, b, text = null, picture = true) {
  const c = 180 - a - b;
  return degQ(n, level, text || `במשולש ABC, ${ang('A', a)} ו-${ang('B', b)}. מה גודל הזווית C?`, c,
    [360 - a - b, 180 - a, 180 - b, a + b, c + 10],
    `${ltr(`180° − ${a}° − ${b}° = ${c}°`)}. בדיקה: ${ltr(`${a}° + ${b}° + ${c}° = 180°`)}.`,
    picture ? { picture: triPic({ angles: [a, b], angleLabels: [deg(a), deg(b), deg(c)] }, ltr(`∠C = ${c}°`)) } : {});
}

/** A base angle of an isosceles triangle from its top angle. */
function baseQ(n, level, top, text) {
  const base = (180 - top) / 2;
  return degQ(n, level, text, base, [180 - top, top, 90 - top / 2 + 10, base + 10],
    `לשתי זוויות הבסיס נשארים ${ltr(`180° − ${top}° = ${180 - top}°`)}, והן שוות: ${ltr(`${180 - top}° ÷ 2 = ${base}°`)}.`,
    { picture: triPic({ angles: [base, base], ticks: [0, 1, 1], angleLabels: [deg(base), deg(base), deg(top)] }, `זוויות הבסיס: ${ltr(`${base}°`)}`) });
}

/** The top angle of an isosceles triangle from a base angle. */
function topQ(n, level, base, text) {
  const top = 180 - 2 * base;
  return degQ(n, level, text, top, [base, 180 - base, 90 - base, top + 10],
    `שתי זוויות הבסיס שוות, ${ltr(`${base}° + ${base}° = ${2 * base}°`)}. לזווית הראש נשארים ${ltr(`180° − ${2 * base}° = ${top}°`)}.`,
    { picture: triPic({ angles: [base, base], ticks: [0, 1, 1], angleLabels: [deg(base), deg(base), deg(top)] }, `זווית הראש: ${ltr(`${top}°`)}`) });
}

