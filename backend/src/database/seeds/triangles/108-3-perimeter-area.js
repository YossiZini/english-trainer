/** Perimeter of three sides: wrong options from forgetting a side, one off. */
function perimeterQ(n, level, [a, b, c], text, picture = true) {
  const p = a + b + c;
  return numQ(n, level, text, p, [a + b, b + c, a + c, p + 1],
    `מחברים את שלוש הצלעות: ${ltr(`${a} + ${b} + ${c} = ${p}`)}.`,
    picture ? { picture: triPic({ sides: [a, b, c].sort((x, y) => y - x), sideLabels: [a, b, c].sort((x, y) => y - x).map(String) }, `היקף: ${ltr(`${a} + ${b} + ${c} = ${p}`)}`) } : {});
}

/** Area from a base and a height: wrong options from forgetting ÷ 2, adding, halving the sum. */
function areaQ(n, level, b, h, text, { apex = null, right = false, question = null } = {}) {
  const area = (b * h) / 2;
  const picture = triPic(right
    ? { base: b, apex: [0, h], sideLabels: [String(b), '', String(h)], angleLabels: ['90°', '', ''] }
    : { base: b, apex: [apex === null ? b / 3 : apex, h], sideLabels: [String(b), '', ''], height: true, heightLabel: String(h) },
  ltr(`${b} × ${h} ÷ 2 = ${area}`));
  return numQ(n, level, text, area, [b * h, b + h, (b + h) / 2, area + 1],
    `${right ? 'הניצבים הם הבסיס והגובה' : 'בסיס כפול גובה, חלקי 2'}: ${ltr(`${b} × ${h} ÷ 2 = ${area}`)}.`,
    { picture, question });
}

