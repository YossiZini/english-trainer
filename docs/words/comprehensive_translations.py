def main():
    print("Loading comprehensive Hebrew translations...")

    # Load words.csv
    words_list = []
    translated_count = 0

    with open('words.csv', 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            if '[TO TRANSLATE]' in row.get('Hebrew Translation', ''):
                english = row['English Word']

                # Try direct match
                if english in TRANSLATIONS:
                    row['Hebrew Translation'] = TRANSLATIONS[english]
                    translated_count += 1
                elif english.lower() in TRANSLATIONS:
                    row['Hebrew Translation'] = TRANSLATIONS[english.lower()]
                    translated_count += 1

            words_list.append(row)

    # Write updated words.csv
    print("Writing updated words.csv...")
    fieldnames = ['English Word', 'Hebrew Translation', 'Difficulty Level', 'Source', 'Example Sentence']

    with open('words.csv', 'w', encoding='utf-8', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(words_list)

    # Count remaining
    remaining = sum(1 for row in words_list if '[TO TRANSLATE]' in row.get('Hebrew Translation', ''))

    print(f"\nDone!")
    print(f"  Translated: {translated_count} words")
    print(f"  Still need translation: {remaining} words")

    if remaining > 0:
        remaining_words = [row for row in words_list if '[TO TRANSLATE]' in row.get('Hebrew Translation', '')]
        with open('still_need_translation.csv', 'w', encoding='utf-8', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(remaining_words)
        print(f"  Created still_need_translation.csv")

if __name__ == '__main__':
    main()
