def append_to_csv(csv_path: str, translations: list):
    """Append new words to the CSV"""
    with open(csv_path, 'a', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        for english, hebrew, level in translations:
            writer.writerow([english, hebrew, level])

